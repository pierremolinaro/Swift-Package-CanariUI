import Foundation

//--------------------------------------------------------------------------------------------------

public func abs (_ inValue : CanariArea) -> CanariArea {
  return .cu2 (abs (inValue.cu2Value))
}

//--------------------------------------------------------------------------------------------------

public func sqrt (_ inValue : CanariArea) -> CanariLength {
  return .cu (Int (sqrt (Double (inValue.cu2Value))))
}

