import AppKit
import CanariGeometry

//--------------------------------------------------------------------------------------------------

public extension CanariPath {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  func normalized (using inRule : Self.Rule) -> CanariPath {
    CanariPath (cgPath: self.cgPath.normalized (using: inRule.cgRule))
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

