import AppKit
import CanariGeometry

//--------------------------------------------------------------------------------------------------

public extension CanariPath {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  func contains (_ inP : CanariPoint, using inRule : Self.Rule) -> Bool {
    return self.mPath.cgPath.contains (inP.ptValue, using: inRule.cgRule)
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

