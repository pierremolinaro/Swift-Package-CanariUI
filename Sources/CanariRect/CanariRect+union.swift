import Foundation

//--------------------------------------------------------------------------------------------------
//  struct CanariRect
//--------------------------------------------------------------------------------------------------

public extension CanariRect {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  func unioning (_ inOtherRect : CanariRect) -> CanariRect {
    if self.isEmpty {
      return inOtherRect
    }else if inOtherRect.isEmpty {
      return self
    }else{
      return CanariRect ([self.bottomLeft, self.topRight, inOtherRect.bottomLeft, inOtherRect.topRight])
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

