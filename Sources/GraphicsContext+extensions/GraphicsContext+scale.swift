import SwiftUI

//--------------------------------------------------------------------------------------------------

public extension GraphicsContext {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  mutating func scale (by inScale : Double, horizontalFlip inHorizontalFlip : Bool = false) {
    self.scaleBy (x: inHorizontalFlip ? -inScale : inScale, y: inScale)
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

