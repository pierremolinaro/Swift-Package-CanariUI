import SwiftUI

//--------------------------------------------------------------------------------------------------

public extension View {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  @ViewBuilder func isDefaultAction (_ inDefaultAction : Bool) -> some View {
    if inDefaultAction {
      self.keyboardShortcut (.defaultAction)
    }else{
      self
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

