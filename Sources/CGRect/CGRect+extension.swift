import Foundation

//--------------------------------------------------------------------------------------------------

public extension CGRect {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  init (center inCenter : CGPoint, size inSize : CGSize) {
    self.init (
      x: inCenter.x - inSize.width / 2.0,
      y: inCenter.y - inSize.height / 2.0,
      width: inSize.width,
      height: inSize.height
    )
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

