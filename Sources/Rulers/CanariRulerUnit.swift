import SwiftUI

//--------------------------------------------------------------------------------------------------

public enum CanariRulerUnit {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  case cm
  case inch

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var string : String {
    switch self {
    case .cm   : "cm"
    case .inch : "inch"
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var length : CanariLength {
    switch self {
    case .cm   : .cm (1)
    case .inch : .inch (1)
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  func doubleValue (for inLength : CanariLength) -> Double {
    switch self {
    case .cm   : inLength.cmValue
    case .inch : inLength.inchValue
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

