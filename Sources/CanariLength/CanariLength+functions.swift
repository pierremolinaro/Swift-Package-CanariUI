import Foundation

//--------------------------------------------------------------------------------------------------

public func abs (_ inValue : CanariLength) -> CanariLength {
  return .cu (abs (inValue.cuValue))
}

//--------------------------------------------------------------------------------------------------

public func square (_ inValue : CanariLength) -> CanariArea {
  return inValue * inValue
}

