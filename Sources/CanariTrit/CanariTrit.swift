import Foundation

//--------------------------------------------------------------------------------------------------

public enum CanariTrit : Int, Hashable, Comparable, Sendable, CaseIterable, Codable {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  case zero = 0
  case one  = 1
  case two  = 2

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
  //MARK: Comparable
  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public static func < (lhs : borrowing Self, rhs : borrowing Self) -> Bool {
    lhs.rawValue < rhs.rawValue
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

