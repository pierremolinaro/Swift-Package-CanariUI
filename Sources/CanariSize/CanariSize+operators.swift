import Foundation

//--------------------------------------------------------------------------------------------------

public func * (_ inLeft : CGFloat, _ inRight : CanariSize) -> CanariSize {
  return CanariSize (width: inLeft * inRight.width, height: inLeft * inRight.height)
}

