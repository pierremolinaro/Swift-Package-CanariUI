import AppKit

//--------------------------------------------------------------------------------------------------

public extension Scanner {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  func myScanBool (_ ioOk : inout Bool) -> Bool {
    if ioOk, let v = self.scanInt (), v >= 0, v <= 1 {
      return v != 0
    }else{
      ioOk = false
      return false
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

