import AppKit

//--------------------------------------------------------------------------------------------------

public extension Scanner {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  func myScanInt32 (_ ioOk : inout Bool) -> Int32 {
    if ioOk, let v = self.scanInt32 () {
      return v
    }else{
      ioOk = false
      return .zero
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

