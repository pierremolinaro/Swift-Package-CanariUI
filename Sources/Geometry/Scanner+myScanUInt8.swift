import AppKit

//--------------------------------------------------------------------------------------------------

public extension Scanner {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  func myScanUInt8 (_ ioOk : inout Bool) -> UInt8 {
    if ioOk, let v = self.scanInt (), v >= 0, v <= 255 {
      return UInt8 (v)
    }else{
      ioOk = false
      return .zero
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

