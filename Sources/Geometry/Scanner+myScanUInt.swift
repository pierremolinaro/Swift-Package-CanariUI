import AppKit

//--------------------------------------------------------------------------------------------------

public extension Scanner {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  func myScanUInt (_ ioOk : inout Bool) -> UInt {
    if ioOk, let v = self.scanInt (), v >= 0 {
      return UInt (v)
    }else{
      ioOk = false
      return .zero
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

