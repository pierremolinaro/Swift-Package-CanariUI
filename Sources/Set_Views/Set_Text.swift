import SwiftUI

//--------------------------------------------------------------------------------------------------

public struct Set_Text : View {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  private let mText : Set <String>

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public init (_ inText : Set <String>) {
    self.mText = inText
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  public var body : some View {
    if self.mText.isEmpty {
      Text ("No value").italic ()
    }else{
      Text (self.mText.joined (separator: ", ")).italic ()
    }
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

