extension Double {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var str1f : String {
    unsafe String (format: "%.1f", self)
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var str2f : String {
    unsafe String (format: "%.2f", self)
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var str3f : String {
    unsafe String (format: "%.3f", self)
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var str3fz : String {
    var s = unsafe String (format: "%.3f", self)
    if s.contains (".") {
      while s.last == "0" {
        s.removeLast ()
      }
      if s.last == "." {
        s.removeLast ()
      }
    }
    return s
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

